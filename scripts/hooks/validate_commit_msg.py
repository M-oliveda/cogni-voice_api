"""Validate that a commit message follows the project's Gitmoji convention.

Used by the ``commit-msg`` hook and by CI. The first line must start with a
Gitmoji shortcode and a space, continue with an uppercase letter, have no
trailing period, and be at most 72 characters long. Messages generated by Git
itself (merges, reverts, autosquash) are accepted unchanged.
"""

import re
import sys
from pathlib import Path

MAX_FIRST_LINE_LENGTH = 72
GITMOJI_PREFIX = re.compile(r"^:[a-z][a-z0-9_]*: ")
GIT_GENERATED_PREFIXES = ("Merge", 'Revert "', "fixup!", "squash!", "amend!")
HELP = """
Expected format:  :<gitmoji>: <Capitalised message>
  - starts with a Gitmoji shortcode followed by a space
  - the message starts with an uppercase letter
  - no trailing period
  - first line at most 72 characters

Examples:
  :sparkles: Add semantic search endpoint
  :bug: Fix token validation issue
  :memo: Update README and MASTERPLAN

Reference: https://gitmoji.dev
"""


def first_line(message: str) -> str:
    """Return the first non-empty, non-comment line of a commit message.

    Args:
        message: The full commit message, possibly with Git comment lines.

    Returns:
        The subject line, or an empty string when there is none.
    """
    for line in message.splitlines():
        if line.strip() and not line.startswith("#"):
            return line
    return ""


def validate(message: str) -> list[str]:
    """Check a commit message against the Gitmoji rules.

    Args:
        message: The full commit message.

    Returns:
        One human-readable error per broken rule; empty when the message is valid.
    """
    subject = first_line(message)
    if not subject:
        return ["The commit message is empty."]
    if subject.startswith(GIT_GENERATED_PREFIXES):
        return []

    errors = []
    prefix = GITMOJI_PREFIX.match(subject)
    if prefix is None:
        errors.append(
            "The message must start with a Gitmoji shortcode followed by a space "
            "(for example ':sparkles: ')."
        )
    elif not subject[prefix.end() :][:1].isupper():
        errors.append("The first letter after the shortcode must be uppercase.")
    if subject.endswith("."):
        errors.append("The first line must not end with a period.")
    if len(subject) > MAX_FIRST_LINE_LENGTH:
        errors.append(
            f"The first line is {len(subject)} characters; "
            f"the maximum is {MAX_FIRST_LINE_LENGTH}."
        )
    return errors


def main(argv: list[str] | None = None) -> int:
    """Validate the commit message stored in the file Git passes to the hook.

    Args:
        argv: Command-line arguments without the program name; defaults to
            ``sys.argv[1:]``.

    Returns:
        ``0`` when the message is valid, ``1`` when it is not, and ``2`` on
        incorrect usage.
    """
    args = sys.argv[1:] if argv is None else argv
    if not args:
        print("Usage: validate_commit_msg.py <commit-message-file>", file=sys.stderr)
        return 2

    message = Path(args[0]).read_text(encoding="utf-8")
    errors = validate(message)
    if not errors:
        return 0

    print("Invalid commit message:", file=sys.stderr)
    print(f"  {first_line(message)}", file=sys.stderr)
    for error in errors:
        print(f"  - {error}", file=sys.stderr)
    print(HELP, file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
